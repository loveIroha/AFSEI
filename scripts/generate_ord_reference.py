"""Generate the ORd 2011 RHS adapter from a pinned Physiome encoding.

The fixed-tissue comparison uses original INa, never the TP replacement/CiPA.
Source downloads stay in .deps; provenance hashes accompany the generated RHS.
"""
import argparse
import hashlib
import html
import json
from pathlib import Path
import re
import urllib.request

REVISION='2593df010620dde185c41853d6264c30b12c4aa1'
CELLML_URL=f'https://models.cellml.org/w/andre/SAN-ORd/rawfile/{REVISION}/Ohara_Rudy_2011.cellml'
CODE_URL='https://models.cellml.org/e/71/Ohara_Rudy_2011.cellml/@@cellml_codegen/C'
CODE_SHA='f6f2e979416149117029043af9718c7fefb590f0b1b05720c2d13847ae9cff92'


def body(code,name):
    start=code.index('{',code.index(name+'('))+1
    end=code.index('\n}',start)
    return code[start:end]


def generate(reference,project):
    code=(reference/'ord_generated.c').read_text(encoding='utf-8')
    if hashlib.sha256(code.encode()).hexdigest()!=CODE_SHA:
        raise ValueError('unexpected generated ORd source; inspect before updating the pinned hash')
    xml=(reference/'ord_pinned.cellml').read_bytes()
    init=body(code,'initConsts').replace('CONSTANTS[0] = 0;','CONSTANTS[0] = celltype;')
    init=init.replace('CONSTANTS[12] = -80;','CONSTANTS[12] = 0;')
    rhs=body(code,'computeRates')
    # Analytic GHK limits. x/expm1(x) also avoids cancellation near zero.
    replacements={
        77:'2*CONSTANTS[6]*ord_exprel(2*ALGEBRAIC[39])*(STATES[2]*exp(2*ALGEBRAIC[39])-.341*CONSTANTS[2])',
        78:'CONSTANTS[6]*ord_exprel(ALGEBRAIC[39])*(.75*STATES[4]*exp(ALGEBRAIC[39])-.75*CONSTANTS[1])',
        79:'CONSTANTS[6]*ord_exprel(ALGEBRAIC[39])*(.75*STATES[6]*exp(ALGEBRAIC[39])-.75*CONSTANTS[3])',
        184:'CONSTANTS[88]*CONSTANTS[6]*ord_exprel(ALGEBRAIC[39])*(STATES[3]*exp(ALGEBRAIC[39])-CONSTANTS[1])',
        186:'CONSTANTS[89]*2*CONSTANTS[6]*ord_exprel(2*ALGEBRAIC[39])*(STATES[9]*exp(2*ALGEBRAIC[39])-.341*CONSTANTS[2])',
    }
    for index,expression in replacements.items():
        pattern=rf'^ALGEBRAIC\[{index}\] = .*?;$'
        rhs,count=re.subn(pattern,f'ALGEBRAIC[{index}] = {expression};',rhs,flags=re.M)
        if count!=1: raise ValueError('unexpected GHK expression layout')
    header=f'''// Mathematical ORd 2011 RHS; generated by scripts/generate_ord_reference.py.
// Physiome revision {REVISION}; code SHA256 {CODE_SHA}.
// Model: O'Hara et al., PLoS Comput Biol 2011, doi:10.1371/journal.pcbi.1002061.
// Encoding attributed to Steve Niederer / Physiome Model Repository.
// Changes: external stimulus only; analytic GHK limits; original INa retained.
#pragma once
#include <cmath>
#ifdef __CUDACC__
#define ORD_INLINE __host__ __device__ inline
#else
#define ORD_INLINE inline
#endif
ORD_INLINE double ord_exprel(double x) {{
    return fabs(x)<1e-7 ? 1-x/2+x*x/12-x*x*x*x/720 : x/expm1(x);
}}
ORD_INLINE void ord_init(double* CONSTANTS,double* STATES,int celltype) {{
{init}
}}
ORD_INLINE void ord_rates(double VOI,const double* CONSTANTS,double* RATES,
                         const double* STATES,double* ALGEBRAIC) {{
{rhs}
}}
ORD_INLINE double ord_ionic_rhs(const double* y,double voltage,const double* constants,double* dy) {{
    double state[41],rates[41],algebraic[198];
    state[0]=voltage;
    for (int j=0;j<40;++j) state[j+1]=y[j];
    ord_rates(1.0,constants,rates,state,algebraic);
    for (int j=0;j<40;++j) dy[j]=rates[j+1];
    return -rates[0];
}}
#undef ORD_INLINE
'''
    (project/'src/afsi_torch/ep/csrc/ord_device.h').write_text(header,encoding='utf-8')
    initial=[None]*41
    for i,value in re.findall(r'^STATES\[(\d+)\] = ([^;]+);',init,re.M):
        initial[int(i)]=float(value)
    if any(v is None for v in initial): raise ValueError('missing native initial state')
    manifest=dict(model='original ORd 2011',doi='10.1371/journal.pcbi.1002061',
        cellml_url=CELLML_URL,cellml_revision=REVISION,
        cellml_sha256=hashlib.sha256(xml).hexdigest(),generated_c_url=CODE_URL,
        generated_c_sha256=CODE_SHA,ionic_states_excluding_voltage=40,calcium_index=8,
        initial_voltage_v=initial[0]/1000,initial_ionic_state=initial[1:],
        modifications=['disable source built-in pulse; use common external tissue stimulus',
                       'analytic removable GHK singularity limits; no parameter rescaling'],
        original_sodium_current=True,physiome_license_metadata='unspecified')
    (project/'src/afsi_torch/ep/ord_provenance.json').write_text(json.dumps(manifest,indent=2)+'\n',encoding='utf-8')
    print('Generated ORd adapter and provenance',flush=True)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--reference-dir',type=Path)
    args=parser.parse_args()
    project=Path(__file__).resolve().parents[1]
    reference=args.reference_dir or project/'.deps/ord_reference'
    if args.reference_dir is None:
        reference.mkdir(parents=True,exist_ok=True)
        for name,url in (('ord_pinned.cellml',CELLML_URL),('ord_codegen.html',CODE_URL)):
            with urllib.request.urlopen(urllib.request.Request(url,headers={'User-Agent':'Mozilla/5.0'}),timeout=30) as r:
                (reference/name).write_bytes(r.read())
        page=(reference/'ord_codegen.html').read_text(encoding='utf-8')
        blocks=re.findall(r'<pre[^>]*>(.*?)</pre>',page,re.S)
        code=next(html.unescape(re.sub(r'<[^>]+>','',b)) for b in blocks if 'computeRates' in b)
        (reference/'ord_generated.c').write_text(code,encoding='utf-8')
    generate(reference,project)


if __name__=='__main__': main()
